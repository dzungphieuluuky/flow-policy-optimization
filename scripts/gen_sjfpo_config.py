HEADER = """# GENERATED by scripts/gen_sjfpo_config.py -- do not hand-edit.
#
# These are exactly the SJFPOConfig defaults. --config overrides the dataclass,
# so a value here that disagrees with the dataclass silently changes the run.
# Regenerate after any default change; tests/test_config_yaml_parity.py enforces
# that this file and the dataclass agree.
"""


def _yaml_value(value):
    """Render a dataclass default as YAML-native text.

    The call ``str()`` turns ``None`` into the literal ``None``. PyYAML reads that
    back as the four-character *string*. The same call turns ``(0.999, 0.999)``
    into a tuple repr, which PyYAML also reads as a string. Both would pass the
    loader silently. Both would then differ from the dataclass.

    Floats need the same care from the other side: ``repr(1e-05)`` is ``1e-05``,
    and YAML 1.1 reads that as a *string*, not a float. The loader then hands
    the config a str where it expects a float. An explicit decimal point fixes
    it, and only the ones that need it are touched.
    """
    if value is None:
        return "null"
    if isinstance(value, tuple):
        return "[" + ", ".join(_yaml_value(v) for v in value) + "]"
    if isinstance(value, float) and "e" in repr(value) and "." not in repr(value):
        return repr(value).replace("e", ".0e", 1)
    return repr(value)


def render() -> str:
    from myfpo.configuration import SJFPOConfig

    cfg = SJFPOConfig()
    lines = [HEADER]
    emitted: set[str] = set()
    for title, names in SECTIONS:
        lines.append(f"\n# -- {title} " + "-" * max(0, 58 - len(title)))
        for name in names:
            if name not in {f.name for f in dataclasses.fields(cfg)}:
                raise SystemExit(f"unknown field in SECTIONS: {name}")
            emitted.add(name)
            lines.append(f"{name}: {_yaml_value(getattr(cfg, name))}")
    known = {f.name for f in dataclasses.fields(cfg)}
    # The SECTIONS table excludes report_to on purpose. It is a reporting sink,
    # not a training knob. Its default is "all", which wandb-side would override.
    skipped = sorted(known - emitted)
    if skipped:
        lines.append("\n# -- Not emitted (non-hyperparameters) " + "-" * 20)
        lines.append(f"# {', '.join(skipped)}")
    return "\n".join(lines) + "\n"


